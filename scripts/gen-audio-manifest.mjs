// Generates src/config/audioManifest.ts by scanning public/audio, and the
// optional music a world ships for itself under public/worlds/<id>/music.
//
// Same contract as the art manifests: a browser cannot list a directory, so
// the catalogue is compiled rather than scanned at runtime, and dropping a
// file in is the whole job — vite.config.ts reruns this on dev-server start,
// on every add or removal while it runs, and at the start of a build.
//
// Runnable by hand: `npm run gen:assets`.

import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { artIn, fileTable, AUDIO_EXTENSIONS } from './artFiles.mjs'
import { AUDIO_FOLDERS, SLOTS_BY_FOLDER, WORLD_MUSIC_SLOTS } from './audioSlots.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
export const AUDIO_DIR = join(ROOT, 'public', 'audio')
const WORLDS_DIR = join(ROOT, 'public', 'worlds')
const OUT = join(ROOT, 'src', 'config', 'audioManifest.ts')

const scan = (dir, slots) => artIn(dir, slots, AUDIO_EXTENSIONS)

function build() {
  const cues = {}
  const files = {}
  const missing = []

  for (const folder of AUDIO_FOLDERS) {
    const found = scan(join(AUDIO_DIR, folder), SLOTS_BY_FOLDER[folder])
    cues[folder] = found.map((a) => a.slot)
    Object.assign(files, fileTable(found, `audio/${folder}/`))
    for (const slot of SLOTS_BY_FOLDER[folder]) {
      if (!cues[folder].includes(slot)) missing.push(`${folder}/${slot}`)
    }
  }

  // A world may ship its own dungeon/battle/boss music. Anything it does not
  // ship falls back to the global track of the same name, so a world needs no
  // music at all to be playable.
  const worldMusic = {}
  const worldIds = existsSync(WORLDS_DIR)
    ? readdirSync(WORLDS_DIR).filter((d) => statSync(join(WORLDS_DIR, d)).isDirectory()).sort()
    : []
  for (const id of worldIds) {
    const found = scan(join(WORLDS_DIR, id, 'music'), WORLD_MUSIC_SLOTS)
    if (found.length === 0) continue
    worldMusic[id] = found.map((a) => a.slot)
    Object.assign(files, fileTable(found, `worlds/${id}/music/`))
  }

  const lit = (v) => JSON.stringify(v)
  const source = `// Generated by scripts/gen-audio-manifest.mjs — do not edit by hand.
// Rewritten when the dev server starts, when audio is added or removed while
// it runs, and at the start of every build.

/** Cue names that have a file behind them, by folder. */
export const audioManifest = {
${AUDIO_FOLDERS.map((f) => `  ${f}: ${lit(cues[f])},`).join('\n')}
} as const

/**
 * Music a world ships for itself, by world id. A slot listed here overrides
 * the global track of the same name for runs in that world.
 */
export const worldMusic: Readonly<Record<string, readonly string[]>> = ${lit(worldMusic)}

/**
 * The file behind each cue, keyed by its path from public/. Cue names are
 * fixed; the file may be any format the browser decodes and any
 * capitalisation, so the name is recorded rather than reconstructed.
 */
export const audioFiles: Readonly<Record<string, string>> = ${JSON.stringify(files, null, 2)}
`
  return { source, cues, worldMusic, missing, total: Object.values(cues).flat().length }
}

export function generateAudioManifest() {
  const r = build()
  const previous = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  const changed = previous !== r.source
  if (changed) {
    mkdirSync(dirname(OUT), { recursive: true })
    writeFileSync(OUT, r.source)
  }
  return { ...r, changed }
}

if (process.argv[1] && process.argv[1].endsWith('gen-audio-manifest.mjs')) {
  const r = generateAudioManifest()
  for (const m of r.missing) console.warn(`gen-audio-manifest: no file for ${m} — that cue stays silent.`)
  const worlds = Object.keys(r.worldMusic)
  console.log(
    `gen-audio-manifest: ${r.total} cues` +
      (worlds.length ? `, own music for ${worlds.join(', ')}` : '') +
      (r.changed ? '' : ' (unchanged)'),
  )
}
