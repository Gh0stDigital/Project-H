// Generates src/config/assetManifest.ts by scanning public/assets.
//
// Why this exists: the asset registry used to be a hand-written list, so
// dropping a PNG into public/assets did nothing until someone remembered to
// add a matching line in TypeScript. A portrait that existed on disk but not
// in that list was simply invisible to the game — which is exactly how
// totem_silverKnight.png went missing. Scanning the folder removes the step
// that can be forgotten.
//
// Runs from postinstall and before every build, so the manifest is always in
// step with the files. Regenerate by hand with `npm run gen:assets`.

import { readdirSync, statSync, writeFileSync, readFileSync, existsSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const ASSETS = join(ROOT, 'public', 'assets')
const OUT = join(ROOT, 'src', 'config', 'assetManifest.ts')

if (!existsSync(ASSETS)) {
  console.error('gen-asset-manifest: no public/assets directory.')
  process.exit(1)
}

const categories = readdirSync(ASSETS)
  .filter((d) => statSync(join(ASSETS, d)).isDirectory())
  .sort()

const manifest = {}
let total = 0
for (const category of categories) {
  const keys = readdirSync(join(ASSETS, category))
    .filter((f) => f.toLowerCase().endsWith('.png'))
    .map((f) => f.slice(0, -4))
    // 'default' first: it is every category's fallback, and listing it first
    // keeps it at the head of any picker built from this order.
    .sort((a, b) => (a === 'default' ? -1 : b === 'default' ? 1 : a.localeCompare(b)))
  if (keys.length === 0) continue
  if (!keys.includes('default')) {
    console.warn(`gen-asset-manifest: ${category}/ has no default.png — lookups will fall back to its first key.`)
  }
  manifest[category] = keys
  total += keys.length
}

const body = Object.entries(manifest)
  .map(([cat, keys]) => `  ${cat}: [${keys.map((k) => `'${k}'`).join(', ')}],`)
  .join('\n')

const out = `// Generated by scripts/gen-asset-manifest.mjs — do not edit by hand.
// Every PNG under public/assets, by category. Add or remove a file and
// rerun \`npm run gen:assets\` (it also runs on install and before a build).

export const assetManifest = {
${body}
} as const
`

mkdirSync(dirname(OUT), { recursive: true })
const prev = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
if (prev !== out) writeFileSync(OUT, out)
console.log(
  `gen-asset-manifest: ${total} images across ${Object.keys(manifest).length} categories` +
    (prev === out ? ' (unchanged)' : ''),
)
