// Compiles public/worlds into src/config/worldManifest.ts.
//
// A world is a folder of art. This walks each one, checks it against the
// pack format in worldSlots.mjs, and records what it found — including,
// for anything incomplete, exactly which files are missing. The app offers
// the complete ones and reports the rest, so a half-finished world is a
// clear message rather than a broken screen.
//
// Runs automatically from the Vite plugin: on dev-server start, on any add
// or removal while it runs, and at the start of every build.

import { readdirSync, statSync, writeFileSync, readFileSync, existsSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  REQUIRED_LOCATIONS,
  OPTIONAL_LOCATIONS,
  REQUIRED_EVENTS,
  MIN_NPCS,
  MIN_ENEMIES,
  WORLD_FOLDERS,
} from './worldSlots.mjs'
import { artIn, fileTable } from './artFiles.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
export const WORLDS_DIR = join(ROOT, 'public', 'worlds')
const OUT = join(ROOT, 'src', 'config', 'worldManifest.ts')

/** Reads optional world.json, falling back to a title made from the id. */
function metaFor(id, dir) {
  const titled = id
    .split(/[-_]/)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ')
  const file = join(dir, 'world.json')
  if (!existsSync(file)) return { name: titled, description: '' }
  try {
    const raw = JSON.parse(readFileSync(file, 'utf8'))
    return {
      name: typeof raw.name === 'string' && raw.name.trim() ? raw.name.trim() : titled,
      description: typeof raw.description === 'string' ? raw.description.trim() : '',
    }
  } catch {
    // A malformed world.json must not stop the world loading — it only
    // costs the pack its title.
    return { name: titled, description: '' }
  }
}

function inspect(id) {
  const dir = join(WORLDS_DIR, id)
  // Required slots are matched ignoring case; npcs and enemies are named by
  // their filenames, so nothing is canonical there.
  const canonical = {
    locations: [...REQUIRED_LOCATIONS, ...OPTIONAL_LOCATIONS],
    events: REQUIRED_EVENTS,
  }
  const art = Object.fromEntries(
    WORLD_FOLDERS.map((folder) => [folder, artIn(join(dir, folder), canonical[folder] ?? [])]),
  )
  const collisions = WORLD_FOLDERS.flatMap((folder) =>
    (art[folder].collisions ?? []).map((c) => ({ ...c, folder })),
  )
  const slots = (folder) => art[folder].map((a) => a.slot)
  const locations = slots('locations')
  const events = slots('events')
  const npcs = slots('npcs')
  const enemies = slots('enemies')
  const bosses = slots('bosses')

  // The file behind each slot, so the app can build a URL for it without
  // guessing at either the extension or the capitalisation. Keyed the way the
  // app asks: "folder/slot".
  const files = Object.assign(
    {},
    ...WORLD_FOLDERS.map((folder) => fileTable(art[folder], `${folder}/`)),
  )

  const missing = []
  for (const slot of REQUIRED_LOCATIONS) {
    if (!locations.includes(slot)) missing.push(`locations/${slot}`)
  }
  for (const slot of REQUIRED_EVENTS) {
    if (!events.includes(slot)) missing.push(`events/${slot}`)
  }
  if (npcs.length < MIN_NPCS) missing.push(`npcs/ needs ${MIN_NPCS}, has ${npcs.length}`)
  if (enemies.length < MIN_ENEMIES) missing.push(`enemies/ needs ${MIN_ENEMIES}, has ${enemies.length}`)

  return {
    id,
    ...metaFor(id, dir),
    complete: missing.length === 0,
    missing,
    locations,
    optionalLocations: OPTIONAL_LOCATIONS.filter((s) => locations.includes(s)),
    events,
    npcs,
    enemies,
    bosses,
    files,
    collisions,
  }
}

function build() {
  const ids = existsSync(WORLDS_DIR)
    ? readdirSync(WORLDS_DIR)
        .filter((d) => statSync(join(WORLDS_DIR, d)).isDirectory())
        .sort()
    : []
  const worlds = ids.map(inspect)

  const lit = (v) => JSON.stringify(v)
  const body = worlds
    .map(
      (w) => `  {
    id: ${lit(w.id)},
    name: ${lit(w.name)},
    description: ${lit(w.description)},
    complete: ${w.complete},
    missing: ${lit(w.missing)},
    locations: ${lit(w.locations)},
    optionalLocations: ${lit(w.optionalLocations)},
    events: ${lit(w.events)},
    npcs: ${lit(w.npcs)},
    enemies: ${lit(w.enemies)},
    bosses: ${lit(w.bosses)},
    files: ${lit(w.files)},
  },`,
    )
    .join('\n')

  const source = `// Generated by scripts/gen-world-manifest.mjs — do not edit by hand.
// Rewritten when the dev server starts, when art under public/worlds is
// added or removed while it runs, and at the start of every build.

export interface WorldPack {
  id: string
  name: string
  description: string
  /** False when a required slot is missing; such a world is never offered. */
  complete: boolean
  /** Exactly what is missing, for the report shown to whoever is building it. */
  missing: readonly string[]
  locations: readonly string[]
  optionalLocations: readonly string[]
  events: readonly string[]
  npcs: readonly string[]
  enemies: readonly string[]
  bosses: readonly string[]
  /**
   * The filename behind each slot, keyed "folder/slot". Slot names are fixed
   * and lower-camel; the file may be any supported format and any
   * capitalisation, so the name is recorded rather than reconstructed.
   */
  files: Readonly<Record<string, string>>
}

export const requiredLocations = ${lit(REQUIRED_LOCATIONS)} as const
export const requiredEvents = ${lit(REQUIRED_EVENTS)} as const
export const minNpcs = ${MIN_NPCS}
export const minEnemies = ${MIN_ENEMIES}

export const worldPacks: readonly WorldPack[] = [
${body}
]
`
  return { worlds, source }
}

export function generateWorldManifest() {
  const { worlds, source } = build()
  const previous = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  const changed = previous !== source
  if (changed) {
    mkdirSync(dirname(OUT), { recursive: true })
    writeFileSync(OUT, source)
  }
  return { changed, worlds }
}

if (process.argv[1] && process.argv[1].endsWith('gen-world-manifest.mjs')) {
  const { worlds, changed } = generateWorldManifest()
  for (const w of worlds) {
    for (const c of w.collisions ?? []) {
      console.warn(
        `gen-world-manifest: ${w.id}/${c.folder} has two files for the "${c.slot}" slot — ` +
          `using ${c.used}, ignoring ${c.ignored}.`,
      )
    }
    if (w.complete) {
      console.log(`gen-world-manifest: ${w.id} ✓ complete (${w.enemies.length} enemies, ${w.npcs.length} NPCs)`)
    } else {
      console.warn(`gen-world-manifest: ${w.id} ✗ incomplete — missing:`)
      for (const m of w.missing) console.warn(`    ${m}`)
    }
  }
  console.log(
    `gen-world-manifest: ${worlds.filter((w) => w.complete).length}/${worlds.length} worlds playable` +
      (changed ? '' : ' (unchanged)'),
  )
}
